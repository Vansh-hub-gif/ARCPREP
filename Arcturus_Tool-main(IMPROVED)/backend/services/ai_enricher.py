def _split_ai_benefit_lines(ai_benefit: str) -> List[str]:
    """
    Turn whatever the model returned into a clean list of candidate benefit
    sentences. Small/instruction-shaky models frequently don't return
    exactly "two lines separated by \\n" even when told to — they add
    numbering ("1. ..."), bullets ("- ..."), markdown bold, a preamble
    ("Here are the two business benefits:"), or just run both sentences
    together in one paragraph. This normalizes all of that instead of
    silently failing validation and falling back to the generic generator.
    """
    text = ai_benefit.strip()

    # Strip a common preamble line like "Here are the business benefits:"
    text = re.sub(
        r"^(here are|here's|below are|the following are)[^\n]*:\s*\n",
        "", text, flags=re.IGNORECASE,
    )

    # Split on newlines first (handles the normal "one per line" case).
    raw_lines = [l for l in text.split("\n") if l.strip()]

    cleaned = []
    for line in raw_lines:
        line = line.strip()
        # Strip leading numbering / bullets / markdown bold markers.
        line = re.sub(r"^(\d+[.)]\s*|[-*•]\s*)", "", line)
        line = line.strip("*").strip()
        if line:
            cleaned.append(line)

    # If the model returned exactly one giant paragraph containing two
    # sentences, split it into two on sentence boundaries so we still get
    # a usable 2-item list instead of failing validation outright.
    if len(cleaned) == 1 and len(cleaned[0].split()) > 25:
        sentences = re.split(r"(?<=[.!?])\s+", cleaned[0])
        sentences = [s.strip() for s in sentences if s.strip()]
        if len(sentences) >= 2:
            cleaned = sentences

    return cleaned


async def enrich_feature(
    feature: Dict[str, Any],
    index: int,
    total: int,
    task_status: Optional[Dict[str, Any]] = None,
    previous_benefits: Optional[List[str]] = None,
) -> Dict[str, Any]:

    title = clean_text(feature.get("title"))
    url = clean_text(feature.get("url"))

    if task_status is not None:
        task_status["processed"] = index - 1
        task_status["current_feature"] = title

    print(f"[ENRICH] {index}/{total}: {title}")

    oracle_detail = await fetch_oracle_detail_text(url)

    if DEBUG_SOURCES:
        try:
            os.makedirs("outputs/debug_sources", exist_ok=True)
            safe_title = re.sub(r"[^a-zA-Z0-9_-]+", "_", title)[:80]
            with open(f"outputs/debug_sources/{index}_{safe_title}.json", "w", encoding="utf-8") as f:
                json.dump(oracle_detail, f, indent=2, ensure_ascii=False)
        except Exception as e:
            print(f"[DEBUG WRITE ERROR] {e}")

    # ---- Generate Business Benefit ----
    description = oracle_detail.get("description_source", "")
    intro = oracle_detail.get("intro_source", "")
    full_text = oracle_detail.get("full_text", "")
    business_benefit = ""
    benefit_origin = "FALLBACK"
    previous_benefits = previous_benefits if previous_benefits is not None else []

    # Everything the model is allowed to reason from — also used as the
    # anti-plagiarism reference for the overlap check.
    source_reference = "\n".join(
        x for x in [
            description,
            intro,
            oracle_detail.get("benefit_source", ""),
            oracle_detail.get("impact_source", ""),
            full_text,
        ] if x
    )

    if not clean_text(source_reference):
        print(f"[CONTEXT THIN] No usable description/benefit/impact text extracted for '{title}'. "
              f"AI generation will be low-confidence.")

    corrective_note = ""
    for attempt in range(1, BENEFIT_MAX_ATTEMPTS + 1):
        try:
            ai_benefit = await generate_benefit_ai(
                title, description, intro, oracle_detail, corrective_note
            )
        except Exception as e:
            print(f"[AI ERROR] attempt {attempt}/{BENEFIT_MAX_ATTEMPTS} for '{title}': {e}")
            await asyncio.sleep(min(2 ** attempt, 8))
            continue

        lines = _split_ai_benefit_lines(ai_benefit or "")
        accepted, reasons = validate_benefit_lines(
            lines,
            source_reference,
            title=title,
            evidence_blob=_source_evidence_blob(oracle_detail, description, intro),
        )

        if len(accepted) == BENEFIT_REQUIRED_LINES:
            candidate = "\n".join(accepted)
            similar_to = _benefit_is_too_similar(candidate, previous_benefits)
            if similar_to:
                corrective_note = (
                    "- The candidate is too similar to a previously generated benefit. "
                    "Write a genuinely feature-specific benefit using this feature's own nouns, "
                    "workflow and documented outcome; do not reuse the same sentence skeleton."
                )
                print(f"[AI REJECTED] cross-feature repetition for '{title}'")
                await asyncio.sleep(0.5)
                continue
            business_benefit = candidate
            benefit_origin = "AI" if attempt == 1 else f"AI_RETRY_{attempt}"
            BENEFIT_RUN_STATS["ai" if attempt == 1 else "ai_retry"] += 1
            print(f"[BENEFIT] AI generated (attempt {attempt}) for: {title}")
            previous_benefits.append(business_benefit)
            break

        # Not enough usable lines — tell the model exactly what was wrong and
        # ask again instead of silently giving up (the old behaviour).
        corrective_note = "\n".join(f"- {r}" for r in reasons[:6]) or \
            f"- exactly two strong Business Benefit statements are required; provide exactly two, no more and no fewer"
        print(f"[AI REJECTED] attempt {attempt}/{BENEFIT_MAX_ATTEMPTS} for '{title}': "
              f"{len(accepted)}/{len(lines)} lines accepted. Reasons: {reasons[:3]}")
        await asyncio.sleep(1)

    if not business_benefit:
        business_benefit = generate_benefit_fallback(title, description, full_text, oracle_detail.get("benefit_source", ""))
        benefit_origin = "FALLBACK"
        BENEFIT_RUN_STATS["fallback"] += 1
        BENEFIT_RUN_STATS["failures"].append(title)
        previous_benefits.append(business_benefit)
        print(f"[BENEFIT FAILURE] AI generation failed after {BENEFIT_MAX_ATTEMPTS} "
              f"attempts for: {title} — Oracle-grounded fallback written, needs review")

    # ---- Description for the "Release Feature" column ----
    # PRIMARY: Oracle's own text for this feature, scraped directly from the
    # feature page. Not AI-generated and not AI-rewritten.
    description_text = clean_text(oracle_detail.get("feature_description", ""))
    description_origin = "ORACLE_SCRAPE"

    # Only if the page genuinely yielded no body prose do we fall back to the
    # older heuristic reconstruction, and we say so in the log.
    if not description_text:
        description_text = make_safe_description_fallback(title, oracle_detail)
        description_origin = "HEURISTIC_FALLBACK"
        print(f"[DESCRIPTION FALLBACK] No Oracle body paragraphs scraped for '{title}' "
              f"— heuristic reconstruction used, needs review")
    else:
        DESCRIPTION_RUN_STATS["scraped"] += 1

    if description_origin != "ORACLE_SCRAPE":
        DESCRIPTION_RUN_STATS["fallback"] += 1
        DESCRIPTION_RUN_STATS["fallback_titles"].append(title)

    # ---- Deterministic fields ----
    action_required = derive_action_required(oracle_detail)
    impact = assess_business_impact(oracle_detail, title)
    mandatory = assess_mandatory(oracle_detail)
    steps_to_enable = extract_steps_concise(oracle_detail)
    access_requirements = extract_access_concise(oracle_detail)

    # ---- Build enriched dict, CLEARING old benefit keys ----
    enriched = dict(feature)
    for key in ["business_benefit", "benefit", "business_value", "Business Benefit", "Benefit"]:
        enriched.pop(key, None)

    enriched.update({
        "title": title,
        "url": url,
        "description": description_text,
        # Provenance so QA can see at a glance which rows are real Oracle text.
        # Additive key only — no existing consumer is affected.
        "description_origin": description_origin,
        "business_benefit": ensure_non_empty_benefit(
            business_benefit, title, description_text, full_text
        ),
        # Provenance so the UI / QA can see which rows are real AI output.
        # Additive key only — no existing consumer is affected.
        "benefit_origin": benefit_origin,
        "action_required": action_required,
        "impact": impact,
        "mandatory": mandatory,
        "steps_to_enable": steps_to_enable,
        "access_requirements": access_requirements,
        "notes": "Validate the setup and business impact in a lower environment before production rollout.",
        "bug_ids": extract_bug_ids(oracle_detail.get("full_text")),
        "oracle_feature_id": extract_feature_id_from_url(url),
    })

    if task_status is not None:
        task_status["processed"] = index

    await asyncio.sleep(REQUEST_DELAY_SECONDS)

    # --- FIXED: return at the correct indentation level ---
    return enriched


