def extract_section_text(soup: BeautifulSoup, heading_names: List[str]) -> str:
    heading_names_l = [clean_text(x).lower() for x in heading_names]
    headings = soup.find_all(["h1", "h2", "h3", "h4", "strong", "b"])
    for heading in headings:
        heading_text = clean_text(heading.get_text(" ")).lower()
        if not any(x in heading_text for x in heading_names_l):
            continue
        collected = []
        seen = set()
        for sibling in heading.find_next_siblings():
            if getattr(sibling, "name", None) in ["h1", "h2", "h3", "h4"]:
                break
            if not getattr(sibling, "name", None):
                continue
            _remove_noise_tags(sibling)
            pieces = []
            tables = sibling.find_all("table")
            if tables:
                for table in tables:
                    for tr in table.find_all("tr"):
                        cells = [clean_text(td.get_text(" ")) for td in tr.find_all(["td", "th"])]
                        cells = [x for x in cells if x]
                        if len(cells) >= 2:
                            pieces.append(" | ".join(cells))
            elif sibling.name in ["ul", "ol"]:
                for li in sibling.find_all("li", recursive=False):
                    pieces.append(li.get_text(" "))
            else:
                granular = sibling.find_all(["p", "li", "td", "th"])
                if granular:
                    for item in granular:
                        pieces.append(item.get_text(" "))
                else:
                    pieces.append(sibling.get_text(" "))
            for piece in pieces:
                _dedupe_append(collected, seen, piece)
        if collected:
            return "\n".join(collected)
    return ""


