def extract_steps_section(soup: BeautifulSoup) -> str:
    headings = soup.find_all(["h1", "h2", "h3", "h4", "strong", "b"])
    for heading in headings:
        heading_text = clean_text(heading.get_text(" ")).lower()
        if not any(x in heading_text for x in STEPS_HEADING_NAMES):
            continue

        raw_pieces: List[str] = []

        for sibling in heading.find_next_siblings():
            name = getattr(sibling, "name", None)
            if not name:
                continue

            sibling_text = clean_text(sibling.get_text(" ")).lower()

            if any(marker in sibling_text for marker in STEPS_SECTION_END_MARKERS):
                if any(sibling_text.startswith(marker) or sibling_text.lstrip().startswith(marker)
                       for marker in STEPS_SECTION_END_MARKERS):
                    break
                for marker in STEPS_SECTION_END_MARKERS:
                    if sibling_text.startswith(marker):
                        break
                else:
                    if name in ["h1", "h2", "h3", "h4", "strong", "b"] or len(sibling_text.split()) <= 8:
                        break
                    continue

            if name in ["h1", "h2", "h3", "h4"]:
                continue

            if name in ["strong", "b"]:
                continue

            _remove_noise_tags(sibling)

            if sibling.name in ["ol", "ul"]:
                for li in sibling.find_all("li", recursive=True):
                    text = clean_client_text(li.get_text(" "))
                    if text and len(text.split()) >= 3:
                        raw_pieces.append(text)
            elif sibling.name == "table":
                for tr in sibling.find_all("tr"):
                    cells = [clean_text(td.get_text(" ")) for td in tr.find_all(["td", "th"])]
                    cells = [x for x in cells if x]
                    if cells:
                        raw_pieces.append(" | ".join(cells))
            elif sibling.name == "p":
                text = clean_client_text(sibling.get_text(" "))
                if text and len(text.split()) >= 3:
                    raw_pieces.append(text)
            elif sibling.name == "dl":
                for dt in sibling.find_all("dt"):
                    text = clean_client_text(dt.get_text(" "))
                    if text:
                        raw_pieces.append(text)
                for dd in sibling.find_all("dd"):
                    text = clean_client_text(dd.get_text(" "))
                    if text and len(text.split()) >= 3:
                        raw_pieces.append(text)
            else:
                items = sibling.find_all(["li", "p"])
                if items:
                    for item in items:
                        text = clean_client_text(item.get_text(" "))
                        if text and len(text.split()) >= 3:
                            raw_pieces.append(text)
                else:
                    text = clean_client_text(sibling.get_text(" "))
                    if text and len(text.split()) >= 3:
                        raw_pieces.append(text)

        if raw_pieces:
            return "\n".join(raw_pieces)

    # Fallback: scan list items
    raw_pieces_fallback: List[str] = []
    step_keywords = [
        "navigate to", "go to", "click", "select",
        "in the", "work area", "search for",
        "on the", "enable the", "disable the",
        "set the", "enter the", "configure",
        "opt in", "sign in", "open the",
    ]
    for list_elem in soup.find_all(["ol", "ul"]):
        list_pieces = []
        all_items = list_elem.find_all("li", recursive=True)
        step_count = 0
        for li in all_items:
            text = clean_client_text(li.get_text(" "))
            if text and len(text.split()) >= 4:
                lower = text.lower()
                if any(kw in lower for kw in step_keywords):
                    step_count += 1
        if len(all_items) >= 2 and step_count / max(len(all_items), 1) >= 0.5:
            for li in all_items:
                text = clean_client_text(li.get_text(" "))
                if text and len(text.split()) >= 3:
                    list_pieces.append(text)
            if list_pieces and len(list_pieces) > len(raw_pieces_fallback):
                raw_pieces_fallback = list_pieces

    if raw_pieces_fallback:
        return "\n".join(raw_pieces_fallback)

    return ""


