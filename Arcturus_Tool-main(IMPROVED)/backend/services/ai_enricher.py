def _strip_page_noise(text: str, title: str) -> str:
    for noise in DESCRIPTION_PREFIX_NOISE:
        pattern = re.compile(re.escape(noise), re.IGNORECASE)
        text = pattern.sub(" ", text)
    title_escaped = re.escape(title.strip())
    text = re.sub(rf"^{title_escaped}\s*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"^Redwood:\s*", "", text, flags=re.IGNORECASE)
    return re.sub(r"\s+", " ", text).strip()


def make_safe_description_fallback(title: str, source: Dict[str, str]) -> str:
    text_parts = []
    for key in ["description_source", "intro_source"]:
        val = source.get(key, "")
        if val and val.strip():
            cleaned = _strip_page_noise(val, title)
            if cleaned.strip():
                text_parts.append(cleaned)

    if not text_parts:
        full = source.get("full_text", "")
        if full:
            cleaned = _strip_page_noise(full[:4000], title)
            if cleaned.strip():
                text_parts.append(cleaned)

    combined_text = "\n".join(text_parts)

    if not combined_text.strip():
        domain = extract_domain_terms(title, source.get("full_text", ""))
        return f"This capability enhances {domain} in Oracle Cloud SCM. Users interact with the feature in the relevant work area."

    sentences = re.split(r"(?<=[.!?])\s+", clean_client_text(combined_text))
    feature_sentences = []
    context_sentences = []

    for s in sentences:
        s = s.strip()
        if not s or len(s.split()) < 8:
            continue
        lower = s.lower()
        if lower.strip(".") == title.lower().strip("."):
            continue

        contaminated = False
        for phrase in DESCRIPTION_CONTAMINATION:
            if phrase in lower:
                contaminated = True
                break
        if contaminated:
            continue

        noisy = False
        for noise in ["steps to enable", "no additional setup", "no additional configuration",
                       "this update introduces", "visual builder studio", "express mode"]:
            if noise in lower:
                noisy = True
                break
        if noisy:
            continue

        for noise in DESCRIPTION_PREFIX_NOISE:
            if noise in lower:
                noisy = True
                break
        if noisy:
            continue

        if lower.startswith(("click ", "select ", "enter ", "navigate ", "go to ", "search for ")):
            continue

        words = set(re.findall(r"[a-z]{3,}", lower))
        filler = {"leverage", "streamline", "optimize", "enhance", "utilize", "facilitate"}
        if len(words & filler) >= 2:
            continue

        word_list = lower.split()
        for i in range(len(word_list) - 3):
            pair = f"{word_list[i]} {word_list[i+1]}"
            rest = " ".join(word_list[i+2:])
            if pair in rest and len(pair) > 5:
                contaminated = True
                break
        if contaminated:
            continue

        if re.match(r"^(with this feature|feature details|key features?|new capabilities?)\s*:", lower):
            continue
        if ": " in s[:40] and not any(c in s[:40] for c in ["e.g.", "i.e.", "https"]):
            continue

        if lower.startswith(("now you can", "now, you can", "now, the", "now the system")):
            s = re.sub(r"^Now\s*,?\s*you\s+can\s+", "Users can ", s, flags=re.IGNORECASE)
            s = re.sub(r"^Now\s*,?\s*the\s+(system|agent|process)\s+", "The \\1 ", s, flags=re.IGNORECASE)
            lower = s.lower()

        if lower.startswith("now,") or lower.startswith("now "):
            context_sentences.append(s)
            continue

        vague_references = [
            "all of these steps", "these capabilities", "this functionality",
            "all these tasks", "these features",
        ]
        is_vague = False
        for vague in vague_references:
            if vague in lower:
                is_vague = True
                break
        if is_vague:
            context_sentences.append(s)
            continue

        is_problem = False
        for indicator in PROBLEM_INDICATORS:
            if indicator in lower:
                is_problem = True
                break

        if is_problem:
            context_sentences.append(s)
        else:
            feature_sentences.append(s)

    good_sentences = feature_sentences if feature_sentences else context_sentences

    if len(good_sentences) >= 2:
        result = " ".join(good_sentences[:2])
        return re.sub(r"\s+", " ", result).strip()

    if len(good_sentences) == 1:
        s1 = good_sentences[0]
        domain = extract_domain_terms(title, source.get("full_text", ""))
        lower_source = source.get("full_text", "")[:4000].lower()
        location_match = re.search(
            r"(?:in|within|on)\s+(?:the\s+)?([\w\s]{3,40}?)\s+(?:page|work\s?area|screen|ui)",
            lower_source,
        )
        if location_match:
            loc = location_match.group(1).strip()
            return f"{s1} This capability is available in the {loc} work area."
        return f"{s1} This applies to {domain} within Oracle Cloud SCM."

    domain = extract_domain_terms(title, source.get("full_text", ""))
    return f"This capability enhances {domain} in Oracle Cloud SCM. Users interact with the feature in the relevant work area."


