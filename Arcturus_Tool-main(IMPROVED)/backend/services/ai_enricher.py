def clean_text(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def coerce_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        parts = []
        for item in value:
            txt = coerce_text(item).strip()
            if txt:
                parts.append(txt)
        return "\n".join(parts)
    if isinstance(value, dict):
        parts = []
        for _, val in value.items():
            txt = coerce_text(val).strip()
            if txt:
                parts.append(txt)
        return "\n".join(parts)
    return str(value)


def repair_broken_words(text: str) -> str:
    for wrong, right in BROKEN_WORD_FIXES.items():
        text = text.replace(wrong, right)
    text = re.sub(
        r"(^|[•\n.?!:]\s*)([A-Z])\s+([a-z]{2,})",
        lambda m: m.group(1) + m.group(2) + m.group(3),
        text,
    )
    return text


def clean_client_text(value: Any) -> str:
    text = coerce_text(value)
    text = text.replace("\u00a0", " ")
    text = repair_broken_words(text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\s+([.,;:])", r"\1", text)
    return text.strip()


def normalize_piece(piece: Any) -> str:
    piece = clean_client_text(piece)
    lower = piece.lower()
    if lower in NOISE_EXACT:
        return ""
    if any(x in lower for x in FRAMEWORK_NOISE_TERMS):
        return ""
    if lower.startswith("javascript must be enabled"):
        return ""
    return piece.strip()


def remove_duplicate_points(points: List[str]) -> List[str]:
    final = []
    seen = set()
    for point in points:
        key = re.sub(r"[^a-z0-9]+", " ", point.lower()).strip()
        if not key or key in seen:
            continue
        seen.add(key)
        final.append(point)
    return final


