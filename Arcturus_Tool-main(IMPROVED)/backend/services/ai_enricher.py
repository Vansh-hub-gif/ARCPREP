async def call_groq(prompt: str, model: str = None, retries: int = 3) -> Optional[str]:
    if not GROQ_API_KEY:
        raise ValueError("GROQ_API_KEY not set")
    if model is None:
        model = GROQ_MODEL
    url = "https://api.groq.com/openai/v1/chat/completions"
    headers = {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"}
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "temperature": 0.25,
        "max_tokens": 350
    }
    for attempt in range(retries):
        try:
            async with httpx.AsyncClient(timeout=60) as client:
                response = await client.post(url, json=payload, headers=headers)
                response.raise_for_status()
                data = response.json()
                return data["choices"][0]["message"]["content"].strip()
        except httpx.HTTPStatusError as e:
            if e.response.status_code == 429:
                wait = 2 ** attempt  # 1s, 2s
                print(f"[GROQ] Rate limited, retrying in {wait}s (attempt {attempt+1}/{retries})")
                await asyncio.sleep(wait)
                continue
            elif e.response.status_code == 400 and "decommissioned" in e.response.text:
                print(f"[GROQ] Model {model} decommissioned, trying fallback {GROQ_FALLBACK_MODEL}")
                return await call_groq(prompt, GROQ_FALLBACK_MODEL, retries)
            else:
                raise
        except (httpx.TimeoutException, httpx.TransportError) as e:
            wait = 2 ** attempt
            print(f"[GROQ] Network error ({e.__class__.__name__}), retrying in {wait}s "
                  f"(attempt {attempt+1}/{retries})")
            await asyncio.sleep(wait)
            continue
    # BUGFIX: this used to `return None`. The caller treated None as
    # "[AI EMPTY]" and dropped silently into the generic fallback, so a
    # transient rate-limit looked identical to a successful-but-empty
    # generation. Raising lets call_ai() fail over to the other provider.
    raise RuntimeError(f"Groq call failed after {retries} attempts (model={model})")


async def call_ai(prompt: str) -> str:
    """
    Single entry point for text generation with cross-provider failover.

    Previously generate_benefit_ai() called exactly one provider and any
    failure went straight to the rule-based fallback, even when a second
    provider was configured and healthy.
    """
    order = ["groq", "gemini"] if AI_PROVIDER != "gemini" else ["gemini", "groq"]
    errors = []
    for provider in order:
        if provider == "groq" and not GROQ_API_KEY:
            errors.append("groq: GROQ_API_KEY not set")
            continue
        if provider == "gemini" and not GEMINI_API_KEY:
            errors.append("gemini: GEMINI_API_KEY not set")
            continue
        try:
            result = await (call_groq(prompt) if provider == "groq" else call_gemini(prompt))
            if result and result.strip():
                return result.strip()
            errors.append(f"{provider}: empty response")
        except Exception as e:
            errors.append(f"{provider}: {e}")
            print(f"[AI] Provider '{provider}' failed: {e}")
    raise RuntimeError("All AI providers failed -> " + " | ".join(errors))

async def call_gemini(prompt: str) -> str:
    if not GEMINI_API_KEY:
        raise ValueError("GEMINI_API_KEY not set")
    try:
        import google.generativeai as genai
        genai.configure(api_key=GEMINI_API_KEY)
        model = genai.GenerativeModel(GEMINI_MODEL)
        response = await asyncio.to_thread(
            model.generate_content,
            prompt,
            generation_config={"temperature": 0.25, "max_output_tokens": 350}
        )
        return response.text.strip()
    except ImportError:
        raise ValueError("google-generativeai library not installed")

