def _lower_first_word(text: str) -> str:
    """
    Lowercase the first character only when doing so is safe.

    "Deliver to Multiple Locations" -> "deliver to Multiple Locations"
    "B2B Message Converter"         -> "B2B Message Converter"   (acronym)
    "Inventory Task Allocation"     -> "inventory Task Allocation"

    Without the acronym check this produced "b2B Message Converter".
    """
    t = clean_text(text)
    if not t:
        return ""

    first_word = t.split()[0]
    stripped = re.sub(r"[^A-Za-z0-9]", "", first_word)

    # Acronyms / product codes (B2B, LPN, OTBI, REST, FBDI, AI) keep their case.
    if len(stripped) >= 2 and stripped[1:2].isupper():
        return t
    if stripped.isupper():
        return t

    return t[:1].lower() + t[1:]


def _describe_capability(clean_title: str, description: str) -> str:
    """
    Turn the feature's own title into a verb phrase, backed by its scraped
    description. Deterministic, feature-specific, and never shared between
    two different features.
    """
    t = clean_text(clean_title)
    lowered = _lower_first_word(t)

    # Titles that already begin with a verb read naturally as a verb phrase.
    verb_starts = (
        "create", "track", "calculate", "review", "use", "deliver", "define",
        "assign", "update", "select", "complete", "derive", "generate",
        "enable", "support", "account for", "receive", "manage", "override",
        "configure", "purge", "export", "perform", "search", "view", "set up",
    )
    if lowered.lower().startswith(verb_starts):
        gerund_map = {
            "create": "creating", "track": "tracking", "calculate": "calculating",
            "review": "reviewing", "use": "using", "deliver": "delivering",
            "define": "defining", "assign": "assigning", "update": "updating",
            "select": "selecting", "complete": "completing", "derive": "deriving",
            "generate": "generating", "enable": "enabling", "support": "supporting",
            "account": "accounting", "receive": "receiving", "manage": "managing",
            "override": "overriding", "configure": "configuring", "purge": "purging",
            "export": "exporting", "perform": "performing", "search": "searching",
            "view": "viewing", "set up": "setting up",
        }
        first = lowered.split()[0]
        if first in gerund_map:
            return gerund_map[first] + lowered[len(first):]
        if lowered.lower().startswith("account for "):
            return "accounting for " + lowered[len("account for "): ]
        return lowered

    # Noun-led features (especially named AI agents/apps) read more naturally
    # as "using the X" than "work with x" in a business-benefit sentence.
    return f"using the {t}"


