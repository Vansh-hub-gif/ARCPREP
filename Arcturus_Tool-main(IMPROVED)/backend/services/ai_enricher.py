async def fetch_oracle_detail_text(url: str) -> Dict[str, str]:
    result = {
        "full_text": "",
        "intro_source": "",
        "description_source": "",
        "impact_source": "",
        "steps_source": "",
        "access_source": "",
        "benefit_source": "",
        # Oracle's own description for this feature, scraped directly.
        # Never AI-generated, never rewritten.
        "feature_description": "",
    }
    if not url or not url.startswith("http"):
        print(f"[FETCH] Invalid URL: {url}")
        return result

    clean_url = url.split("#")[0]
    try:
        async with httpx.AsyncClient(timeout=30, follow_redirects=True) as client:
            response = await client.get(
                clean_url,
                headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"}
            )
            response.raise_for_status()
    except Exception as e:
        print(f"[FETCH ERROR] {clean_url} -> {e}")
        return result

    soup = BeautifulSoup(response.text, "html.parser")
    for tag in soup(["script", "style", "nav", "footer", "header"]):
        tag.decompose()

    result["full_text"] = clean_text(soup.get_text(" "))[:50000]

    # ---- FEATURE DESCRIPTION: direct Oracle scrape, computed FIRST --------
    # This is the authoritative Feature Description. It is deliberately
    # independent of description_source (which exists only to feed the AI
    # Business Benefit prompt) so that prompt-grooming changes can never
    # again silently alter what the customer reads in the deck.
    # Oracle detail pages often do not render the feature title as an h1/h2.
    # Use the actual feature title supplied by the caller.
    result["feature_description"] = extract_oracle_feature_description(soup, "")

    result["intro_source"] = extract_intro_text(soup)
    # Order matters: an explicit Overview/Description heading wins, then the
    # document-order body walk, then the (fragile) sibling-based intro.
    result["description_source"] = (
        extract_section_text(soup, ["overview", "description", "feature summary", "details"])
        or extract_feature_body_text(soup)
        or result["intro_source"]
    )
    # Previously initialised to "" and never assigned. See
    # extract_oracle_benefit_section() for why that mattered.
    result["benefit_source"] = extract_oracle_benefit_section(soup)
    result["impact_source"] = extract_section_text(
        soup, ["impact", "business impact", "things to consider", "tips and considerations"]
    )
    result["steps_source"] = extract_steps_section(soup)
    result["access_source"] = extract_section_text(
        soup, ["access requirements", "role information"]
    )

    return result


