def _content_tokens(text: str) -> set:
    words = re.findall(r"[a-z0-9]+", (text or "").lower())
    return {w for w in words if w not in _STOPWORDS and len(w) > 2}


def _source_overlap_ratio(line: str, source_text: str) -> float:
    """
    Fraction of the candidate line's content words that also appear in a
    single sentence of the source. High values mean the model copied or
    lightly paraphrased Oracle's wording rather than reasoning about it.
    """
    line_tokens = _content_tokens(line)
    if not line_tokens:
        return 1.0
    best = 0.0
    for sentence in re.split(r"(?<=[.!?])\s+", source_text or ""):
        if len(sentence.split()) < 6:
            continue
        overlap = len(line_tokens & _content_tokens(sentence)) / len(line_tokens)
        best = max(best, overlap)
    return best



