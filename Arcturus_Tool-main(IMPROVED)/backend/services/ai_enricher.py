async def enrich_all_features(
    features: List[Dict[str, Any]],
    task_status: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, Any]]:

    results = []
    total = len(features)
    previous_benefits: List[str] = []

    BENEFIT_RUN_STATS.update({"ai": 0, "ai_retry": 0, "fallback": 0, "failures": []})
    DESCRIPTION_RUN_STATS.update({"scraped": 0, "fallback": 0, "fallback_titles": []})

    for idx, feature in enumerate(features, start=1):
        try:
            enriched = await enrich_feature(feature, idx, total, task_status, previous_benefits)
            results.append(enriched)
        except Exception as exc:
            print(f"[ENRICHMENT ERROR] {feature.get('title')} -> {exc}")
            import traceback
            traceback.print_exc()
            fallback = dict(feature)
            for key in ["business_benefit", "benefit", "business_value", "Business Benefit", "Benefit"]:
                fallback.pop(key, None)
            fallback.update({
                "description": "Oracle documentation extraction failed.",
                # Was "" — that produced genuinely blank Business Benefit
                # cells in the Excel output.
                "business_benefit": ensure_non_empty_benefit(
                    "", clean_text(feature.get("title")), "", ""
                ),
                "benefit_origin": "ERROR",
                "action_required": "Review Required",
                "impact": "REVIEW REQUIRED - assess impact on current business processes",
                "steps_to_enable": "No",
                "access_requirements": "",
                "notes": "Review Oracle source documentation manually.",
            })
            results.append(fallback)

    # ---- FINAL SAFETY NET -------------------------------------------------
    # Nothing downstream is allowed to receive a blank Business Benefit, and
    # two unrelated features are not allowed to share one description.
    seen_descriptions: Dict[str, str] = {}
    duplicate_descriptions: List[str] = []

    for item in results:
        item_title = clean_text(item.get("title"))

        if not clean_text(item.get("business_benefit")):
            item["business_benefit"] = ensure_non_empty_benefit(
                "", item_title, clean_text(item.get("description")), ""
            )
            item["benefit_origin"] = "GUARDED_FALLBACK"

        desc_key = re.sub(r"[^a-z0-9]+", " ", clean_text(item.get("description")).lower()).strip()
        if desc_key:
            if desc_key in seen_descriptions:
                duplicate_descriptions.append(
                    f"{item_title}  ==  {seen_descriptions[desc_key]}"
                )
            else:
                seen_descriptions[desc_key] = item_title

    blank_benefits = [
        clean_text(i.get("title")) for i in results
        if not clean_text(i.get("business_benefit"))
    ]

    print("=" * 70)
    print(f"[DESCRIPTION SUMMARY] {DESCRIPTION_RUN_STATS['scraped']}/{total} "
          f"scraped directly from Oracle, "
          f"{DESCRIPTION_RUN_STATS['fallback']} used the heuristic fallback.")
    if DESCRIPTION_RUN_STATS["fallback_titles"]:
        print("[DESCRIPTION SUMMARY] Features with no scrapable Oracle body text:")
        for t in DESCRIPTION_RUN_STATS["fallback_titles"]:
            print(f"   - {t}")
    if duplicate_descriptions:
        print("[DESCRIPTION WARNING] Features sharing an identical description "
              "(investigate — this should not happen):")
        for pair in duplicate_descriptions:
            print(f"   - {pair}")
    else:
        print("[DESCRIPTION SUMMARY] No duplicate descriptions detected.")
    print(f"[BENEFIT GUARD] Blank Business Benefit cells after guard: "
          f"{len(blank_benefits)}")

    # ---- Loud run summary: silent fallbacks were the core complaint ----
    ai_ok = BENEFIT_RUN_STATS["ai"] + BENEFIT_RUN_STATS["ai_retry"]
    print("=" * 70)
    print(f"[BENEFIT SUMMARY] {ai_ok}/{total} AI-generated "
          f"(first attempt: {BENEFIT_RUN_STATS['ai']}, "
          f"after retry: {BENEFIT_RUN_STATS['ai_retry']}), "
          f"{BENEFIT_RUN_STATS['fallback']} fell back.")
    if BENEFIT_RUN_STATS["failures"]:
        print("[BENEFIT SUMMARY] Features needing manual review:")
        for t in BENEFIT_RUN_STATS["failures"]:
            print(f"   - {t}")
    print("=" * 70)

    if task_status is not None:
        task_status["processed"] = len(results)
        task_status["current_feature"] = None
        task_status["benefit_stats"] = dict(BENEFIT_RUN_STATS)
        task_status["description_stats"] = dict(DESCRIPTION_RUN_STATS)

    return results