def _remove_noise_tags(node) -> None:
    for tag in node.find_all(["script", "style", "img", "svg", "figure", "noscript"]):
        tag.decompose()


def _dedupe_append(collected: List[str], seen: set, piece: str) -> None:
    piece = normalize_piece(piece)
    if not piece:
        return
    key = re.sub(r"[^a-z0-9]+", " ", piece.lower()).strip()
    if not key or key in seen:
        return
    seen.add(key)
    collected.append(piece)


def extract_intro_text(soup: BeautifulSoup) -> str:
    heading = soup.find(["h1"])
    if not heading:
        return ""
    collected = []
    seen = set()
    for sibling in heading.find_next_siblings():
        if getattr(sibling, "name", None) in ["h1", "h2", "h3", "h4"]:
            break
        if not getattr(sibling, "name", None):
            continue
        _remove_noise_tags(sibling)
        text = sibling.get_text(" ")
        _dedupe_append(collected, seen, text)
    return "\n".join(collected)


# Section headings that mark the END of the free-form feature description on
# an Oracle readiness "What's New" feature page.
FEATURE_BODY_END_MARKERS = [
    "business benefit", "steps to enable", "tips and considerations",
    "key resources", "access requirements", "role information",
    "enablement", "watch a demo", "related", "additional information",
]


def _looks_like_section_heading(text: str) -> bool:
    t = clean_text(text).lower().rstrip(":").strip()
    if not t or len(t) > 60:
        return False
    return any(t.startswith(m) or t == m for m in FEATURE_BODY_END_MARKERS)


def extract_feature_body_text(soup: BeautifulSoup) -> str:
    """
    Pull the free-form feature description in DOCUMENT ORDER.

    Why this exists: the previous implementation used
    ``h1.find_next_siblings()``. On Oracle readiness pages the description
    paragraphs are frequently nested inside wrapper <div>s rather than being
    literal siblings of the <h1>, so that call returned nothing and
    ``description_source`` came back empty for a large share of features.
    An empty description meant the AI prompt carried almost no feature
    context, which is the single biggest driver of weak / rejected
    Business Benefit generations.

    This version walks every <p>/<li>/<td> after the title in document order
    and stops at the first recognised section heading.
    """
    heading = soup.find(["h1", "h2"])
    if not heading:
        nodes = soup.find_all(["p", "li"])
    else:
        nodes = heading.find_all_next(["p", "li", "h1", "h2", "h3", "h4", "strong", "b"])

    collected: List[str] = []
    seen: set = set()
    for node in nodes:
        name = getattr(node, "name", None)
        text = clean_text(node.get_text(" "))
        if not text:
            continue
        if name in ("h1", "h2", "h3", "h4", "strong", "b"):
            if _looks_like_section_heading(text):
                break
            continue
        if _looks_like_section_heading(text):
            break
        piece = normalize_piece(text)
        if not piece or len(piece.split()) < 4:
            continue
        _dedupe_append(collected, seen, piece)
        if len(" ".join(collected)) > 6000:
            break
    return "\n".join(collected)


